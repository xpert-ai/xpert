export type DimensionStudioI18n = ReturnType<typeof createDimensionStudioI18n>

export function createDimensionStudioI18n(locale?: string) {
	const normalized = normalizeLocale(locale)
	const catalog = normalized === 'zh-Hans' ? zhHans : normalized === 'zh-Hant' ? zhHant : enUS
	return {
		locale: normalized,
		t(key: DimensionStudioMessageKey, values: MessageValues = {}) {
			return Object.entries(values).reduce(
				(message, [name, value]) => message.split(`{{${name}}}`).join(String(value)),
				catalog[key]
			)
		}
	}
}
