export type CubeWorkbenchI18n = ReturnType<typeof createCubeWorkbenchI18n>

export function createCubeWorkbenchI18n(locale?: string) {
	const normalized = normalizeLocale(locale)
	const catalog = normalized === 'zh-Hans' ? zhHans : normalized === 'zh-Hant' ? zhHant : enUS
	return {
		locale: normalized,
		t(key: CubeWorkbenchMessageKey) {
			return catalog[key]
		}
	}
}
