export type VirtualCubeI18n = ReturnType<typeof createVirtualCubeI18n>

export function createVirtualCubeI18n(locale?: string) {
	const normalized = normalizeLocale(locale)
	const catalog = normalized === 'zh-Hans' ? zhHans : normalized === 'zh-Hant' ? zhHant : enUS
	return {
		locale: normalized,
		t(key: VirtualCubeMessageKey, values: MessageValues = {}) {
			return Object.entries(values).reduce(
				(message, [name, value]) => message.split(`{{${name}}}`).join(String(value)),
				catalog[key]
			)
		}
	}
}
