export function texts(locale: string): Catalog {
    return locale.toLowerCase().startsWith('zh') ? zh : en
}
export function statusText(catalog: Catalog, status?: string | null) {
    if (status === 'failed') return catalog.failedRun
    return status && Object.hasOwn(catalog, status) ? catalog[status as keyof Catalog] : status || catalog.unknown
}
