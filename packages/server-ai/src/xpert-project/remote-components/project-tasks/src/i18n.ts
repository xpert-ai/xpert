export const texts = (locale: string): Texts => (locale.startsWith('zh') ? zh : en)
export function dateTime(value: string | null | undefined, locale: string, short = false) {
    if (!value || !Number.isFinite(Date.parse(value))) return '—'
    return new Intl.DateTimeFormat(locale, {
        ...(short ? {} : { month: '2-digit', day: '2-digit' }),
        hour: '2-digit',
        minute: '2-digit',
        hour12: false
    }).format(new Date(value))
}
export function runtimeLabel(status: string | undefined, t: Texts) {
    switch (status) {
        case 'success':
            return t.success
        case 'error':
        case 'failed':
            return t.failed
        case 'running':
            return t.running
        case 'pending':
            return t.pending
        case 'interrupted':
            return t.interrupted
        case 'timeout':
            return t.timeout
        case 'cancelled':
            return t.cancelled
        case 'unknown':
            return t.unknownStatus
        default:
            return status || t.unknownStatus
    }
}
export function outcomeLabel(value: string | null | undefined, t: Texts) {
    return value === 'accepted'
        ? t.accepted
        : value === 'rejected'
          ? t.rejected
          : value === 'cancelled'
            ? t.cancelled
            : value
}
