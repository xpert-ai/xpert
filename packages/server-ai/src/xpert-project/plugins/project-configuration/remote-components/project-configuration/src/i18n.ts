export function configurationI18n(locale: string) {
    const normalized = locale.replace(/_/g, '-').toLowerCase()
    const chinese = ['zh', 'zh-cn', 'zh-hans', 'zh-hans-cn', 'zh-sg'].includes(normalized)
    const language = chinese ? 'zh-Hans' : 'en-US'
    const catalog = chinese ? zh : en
    return {
        locale: language,
        t: (key: Key, values: Record<string, string | number> = {}) =>
            catalog[key].replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? '')),
        number: (value: number) => new Intl.NumberFormat(language, { maximumFractionDigits: 2 }).format(value)
    }
}
