export function i18n(locale: string) {
  const aliases: Record<string, string> = {
    zh: 'zh-Hans',
    'zh-CN': 'zh-Hans',
    zh_CN: 'zh-Hans',
    zh_Hans: 'zh-Hans',
    en_US: 'en-US',
    en: 'en-US'
  }
  const normalized = aliases[locale] ?? locale
  const language = normalized === 'zh-Hans' ? 'zh-Hans' : 'en-US'
  const catalog = language === 'zh-Hans' ? zh : en
  return {
    locale: language,
    t: (key: Key, values: Record<string, string | number> = {}) =>
      catalog[key].replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? '')),
    time: (value: string | number, timeZone?: string) =>
      new Intl.DateTimeFormat(language, { hour: '2-digit', minute: '2-digit', timeZone }).format(new Date(value)),
    day: (value: string | number, timeZone?: string) =>
      new Intl.DateTimeFormat(language, { month: 'numeric', day: 'numeric', timeZone }).format(new Date(value)),
    date: (value: string | number, timeZone?: string) =>
      new Intl.DateTimeFormat(language, { dateStyle: 'medium', timeStyle: 'short', timeZone }).format(new Date(value)),
    number: (value: number) => new Intl.NumberFormat(language, { maximumFractionDigits: 2 }).format(value),
    currency: (value: number, currency: string) => {
      try {
        return new Intl.NumberFormat(language, { style: 'currency', currency, maximumFractionDigits: 5 }).format(value)
      } catch {
        return `${new Intl.NumberFormat(language).format(value)} ${currency}`
      }
    }
  }
}
export const I18nContext = createContext(i18n('en-US'))
export const useI18n = () => useContext(I18nContext)
